export function getRiskLabel(lang: string, score: number): string {
  const L = getLanguage(lang);
  if (score <= 30) return riskLabels[L].low;
  if (score <= 60) return riskLabels[L].medium;
  if (score <= 80) return riskLabels[L].high;
  return riskLabels[L].critical;
}

